// LiteChat: a lightweight desktop client for WhatsApp Web.
// Uses WebView2 (already part of Windows) instead of bundling a whole browser.
#![windows_subsystem = "windows"]

use std::path::PathBuf;
use std::process::Command;

use tao::{
    dpi::LogicalSize,
    event::{Event, WindowEvent},
    event_loop::{ControlFlow, EventLoopBuilder},
    window::{Icon, WindowBuilder},
};
use tray_icon::{
    menu::{Menu, MenuEvent, MenuItem, PredefinedMenuItem},
    MouseButton, MouseButtonState, TrayIconBuilder, TrayIconEvent,
};
use webview2_com::Microsoft::Web::WebView2::Win32::{
    ICoreWebView2_19, COREWEBVIEW2_MEMORY_USAGE_TARGET_LEVEL_LOW,
    COREWEBVIEW2_MEMORY_USAGE_TARGET_LEVEL_NORMAL,
};
use windows_core::Interface;
use wry::{
    NewWindowResponse, WebContext, WebView, WebViewBuilder, WebViewBuilderExtWindows,
    WebViewExtWindows,
};

/// While the window is hidden, ask WebView2 to release memory
/// (notifications keep arriving); back to normal when it is shown again.
fn set_low_memory(webview: &WebView, low: bool) {
    if let Ok(wv) = webview.webview().cast::<ICoreWebView2_19>() {
        let level = if low {
            COREWEBVIEW2_MEMORY_USAGE_TARGET_LEVEL_LOW
        } else {
            COREWEBVIEW2_MEMORY_USAGE_TARGET_LEVEL_NORMAL
        };
        unsafe {
            let _ = wv.SetMemoryUsageTargetLevel(level);
        }
    }
}

const APP_NAME: &str = "LiteChat";
/// Previous app name: its data folder is migrated so the QR login is kept.
const OLD_APP_NAME: &str = "Talkapp";
const WHATSAPP_URL: &str = "https://web.whatsapp.com/";

/// Extra WebView2 flags: turn off Edge services that are useless here
/// and reduce background processes/memory.
/// Measured: --disable-gpu ~ -95 MB (GPU process), --lite-mode ~ -160 MB (page),
/// together ~ -43% RAM with no CPU increase.
const BROWSER_ARGS: &str = "--disable-features=msWebOOUI,msPdfOOUI,msSmartScreenProtection,\
msEdgeTranslate,msShoppingTrigger,msEdgeCollections,AutofillServerCommunication \
--disable-background-networking --disable-component-update --disable-sync \
--no-first-run --disable-default-apps \
--disable-gpu --disable-gpu-compositing --js-flags=--lite-mode";

enum UserEvent {
    Tray(TrayIconEvent),
    Menu(MenuEvent),
    Title(String),
}

/// Domains that stay inside the app; everything else opens in the browser.
fn is_internal(url: &str) -> bool {
    let host = url
        .split("://")
        .nth(1)
        .and_then(|rest| rest.split(['/', '?', '#']).next())
        .unwrap_or("");
    url.starts_with("about:")
        || url.starts_with("blob:")
        || url.starts_with("data:")
        || host == "whatsapp.com"
        || host.ends_with(".whatsapp.com")
        || host.ends_with(".whatsapp.net")
}

fn open_external(url: &str) {
    if url.starts_with("http://") || url.starts_with("https://") || url.starts_with("mailto:") {
        let _ = Command::new("rundll32")
            .args(["url.dll,FileProtocolHandler", url])
            .spawn();
    }
}

fn data_dir() -> PathBuf {
    let base = std::env::var_os("LOCALAPPDATA")
        .map(PathBuf::from)
        .unwrap_or_else(std::env::temp_dir);
    let dir = base.join(APP_NAME);
    let old = base.join(OLD_APP_NAME);
    if !dir.exists() && old.exists() {
        let _ = std::fs::rename(&old, &dir);
    }
    dir
}

/// 64x64 RGBA icon (white feather in a green bubble), generated by tools/make-icon.ps1.
const ICON_RGBA: &[u8] = include_bytes!("../assets/icon64.rgba");

fn main() -> wry::Result<()> {
    let event_loop = EventLoopBuilder::<UserEvent>::with_user_event().build();

    // Forward tray and menu events to the main event loop.
    let proxy = event_loop.create_proxy();
    TrayIconEvent::set_event_handler(Some(move |e| {
        let _ = proxy.send_event(UserEvent::Tray(e));
    }));
    let proxy = event_loop.create_proxy();
    MenuEvent::set_event_handler(Some(move |e| {
        let _ = proxy.send_event(UserEvent::Menu(e));
    }));

    const ICON_SIZE: u32 = 64;
    let rgba = ICON_RGBA.to_vec();

    let window = WindowBuilder::new()
        .with_title(APP_NAME)
        .with_inner_size(LogicalSize::new(1100.0, 760.0))
        .with_min_inner_size(LogicalSize::new(480.0, 400.0))
        .with_window_icon(Icon::from_rgba(rgba.clone(), ICON_SIZE, ICON_SIZE).ok())
        .build(&event_loop)
        .expect("failed to create the window");

    // Tray menu
    let tray_menu = Menu::new();
    let item_show = MenuItem::new(format!("Open {APP_NAME}"), true, None);
    let item_reload = MenuItem::new("Reload", true, None);
    let item_quit = MenuItem::new("Quit", true, None);
    let _ = tray_menu.append_items(&[
        &item_show,
        &item_reload,
        &PredefinedMenuItem::separator(),
        &item_quit,
    ]);
    let tray = TrayIconBuilder::new()
        .with_tooltip(APP_NAME)
        .with_icon(tray_icon::Icon::from_rgba(rgba, ICON_SIZE, ICON_SIZE).unwrap())
        .with_menu(Box::new(tray_menu))
        .with_menu_on_left_click(false)
        .build()
        .ok();

    // Persistent profile: the QR code only needs to be scanned once.
    let mut web_context = WebContext::new(Some(data_dir()));
    let proxy = event_loop.create_proxy();

    let webview = WebViewBuilder::new_with_web_context(&mut web_context)
        .with_url(WHATSAPP_URL)
        .with_additional_browser_args(match std::env::var("LITECHAT_EXTRA_ARGS") {
            Ok(extra) => format!("{BROWSER_ARGS} {extra}"),
            Err(_) => BROWSER_ARGS.to_string(),
        })
        .with_devtools(cfg!(debug_assertions))
        .with_navigation_handler(|url| {
            if is_internal(&url) {
                true
            } else {
                open_external(&url);
                false
            }
        })
        .with_new_window_req_handler(|url, _features| {
            open_external(&url);
            NewWindowResponse::Deny
        })
        .with_document_title_changed_handler(move |title| {
            let _ = proxy.send_event(UserEvent::Title(title));
        })
        .build(&window)?;

    let show_window = |w: &tao::window::Window, wv: &WebView| {
        set_low_memory(wv, false);
        w.set_visible(true);
        w.set_minimized(false);
        w.set_focus();
    };
    let hide_window = |w: &tao::window::Window, wv: &WebView| {
        w.set_visible(false);
        set_low_memory(wv, true);
    };

    event_loop.run(move |event, _, control_flow| {
        *control_flow = ControlFlow::Wait;
        let _ = &tray; // keep the tray icon alive

        match event {
            // The close button hides to the tray, so notifications keep arriving.
            Event::WindowEvent { event: WindowEvent::CloseRequested, .. } => {
                hide_window(&window, &webview);
            }
            Event::UserEvent(UserEvent::Title(title)) => {
                // WhatsApp Web puts the unread chat count in the title: "(3) WhatsApp"
                let unread = title
                    .strip_prefix('(')
                    .and_then(|t| t.split(')').next())
                    .filter(|n| n.chars().all(|c| c.is_ascii_digit()));
                let label = match unread {
                    Some(n) => format!("({n}) {APP_NAME}"),
                    None => APP_NAME.to_string(),
                };
                window.set_title(&label);
                if let Some(t) = &tray {
                    let _ = t.set_tooltip(Some(&label));
                }
            }
            Event::UserEvent(UserEvent::Tray(TrayIconEvent::Click {
                button: MouseButton::Left,
                button_state: MouseButtonState::Up,
                ..
            })) => {
                if window.is_visible() && !window.is_minimized() {
                    hide_window(&window, &webview);
                } else {
                    show_window(&window, &webview);
                }
            }
            Event::UserEvent(UserEvent::Menu(e)) => {
                if e.id == item_show.id() {
                    show_window(&window, &webview);
                } else if e.id == item_reload.id() {
                    let _ = webview.reload();
                } else if e.id == item_quit.id() {
                    *control_flow = ControlFlow::Exit;
                }
            }
            _ => {}
        }
    });
}
